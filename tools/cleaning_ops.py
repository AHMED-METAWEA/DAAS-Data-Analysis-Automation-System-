_MAX_SAMPLES = 5

# Strings that mean "missing" regardless of the column's pandas dtype.
NULL_TOKENS: set[str] = (
    {
        "", "-", "--", "?", "??", "n/a", "n.a.", "na", "nan", "none", "null", "nil",
        "unknown", "unspecified", "not available", "not specified", "missing",
        "tbd", "tba", "error", "err", "#n/a", "#value!", "#ref!", "#div/0!",
        "\\n", "<na>", "(blank)", "blank", "empty",
    }
    | {p.lower() for p in ARABIC_PLACEHOLDERS}
    | {normalize_arabic(p).lower() for p in ARABIC_PLACEHOLDERS}
)

# Numeric values conventionally used as "missing" sentinels. Only ever applied
# when the caller names them explicitly — see `replace_sentinels`.
COMMON_SENTINELS: tuple[float, ...] = (-1, -99, -999, -9999, 9999, 99999, -999999, 999999)

_TRUE_TOKENS = {"true", "t", "yes", "y", "1", "1.0", "on", "نعم", "صح", "صحيح"}
_FALSE_TOKENS = {"false", "f", "no", "n", "0", "0.0", "off", "لا", "خطا", "خطأ"}

# Decoration that may legitimately surround a number: currency symbols and
# codes, percent signs, and any flavour of space. Deliberately a closed list —
# stripping "everything that is not a digit" turns the identifier "A1" into 1
# and the date "2024-01-05" into 20240105, silently coercing codes and dates
# into numbers that were never in the data.
_DECORATION_RE = re.compile(
    r"[$€£¥₹﷼%٪\s  ]|\b(?:usd|eur|gbp|egp|sar|aed|kwd|jod|qar|bhd|try|inr)\b"
    r"|ج\.م|ر\.س|د\.إ|د\.ك",
    re.IGNORECASE,
)
# What is left must be a number and nothing else.
_STRICT_NUMBER_RE = re.compile(r"^[+-]?[\d.,]*\d[\d.,]*(?:[eE][+-]?\d+)?$")
# A single trailing comma group of 1-2 digits is a decimal comma, never a
# thousands separator (thousands groups are always exactly three digits).
_DECIMAL_COMMA_RE = re.compile(r"^[+-]?\d+,\d{1,2}$")
_EU_DECIMAL_RE = re.compile(r"^\s*[^\d\-+]*[-+]?\d{1,3}(\.\d{3})+,\d+\s*[^\d]*$")
_US_DECIMAL_RE = re.compile(r"^\s*[^\d\-+]*[-+]?\d{1,3}(,\d{3})+\.\d+\s*[^\d]*$")
_DMY_RE = re.compile(r"^\s*(\d{1,2})[/\-.](\d{1,2})[/\-.](\d{2,4})\s*$")
# Year-first values are unambiguous and must never be touched by `dayfirst`.
_YMD_RE = re.compile(r"^\s*\d{4}[/\-.]\d{1,2}[/\-.]\d{1,2}")

# Excel serial dates (1900 date system) and epoch timestamps, by magnitude.
_EXCEL_SERIAL_RANGE = (20000, 80000)      # 1954-10-03 .. 2118-12-31
_EPOCH_SECONDS_RANGE = (5e8, 4e9)         # 1985 .. 2096
_EPOCH_MILLIS_RANGE = (5e11, 4e12)


# ══════════════════════════════════════════════════════════════════════
# Value-level parsing helpers (pure, dtype-safe, individually testable)
# ══════════════════════════════════════════════════════════════════════


def _as_text(series: pd.Series) -> pd.Series:
    """Object-dtype view of a series' values as stripped strings, with real
    nulls preserved. Works for mixed-dtype columns, which is the whole point:
    the previous implementation gated on ``is_string_dtype`` and therefore
    silently skipped every column that mixed strings with numbers — exactly
    the messiest, most in-need-of-cleaning columns in a real file.
    """
    out = series.astype(object).where(series.notna())
    return out.map(lambda v: v.strip() if isinstance(v, str) else v)


def null_token_mask(series: pd.Series) -> pd.Series:
    """Boolean mask of values that are placeholder-for-missing strings.

    dtype-agnostic by construction — a column holding ``["UNKNOWN", 5, 3,
    "N/A", 7]`` is object dtype, and this still finds both placeholders.
    """
    text = _as_text(series)
    return text.map(
        lambda v: isinstance(v, str) and normalize_arabic(v).casefold() in NULL_TOKENS
    ).fillna(False).astype(bool)


def infer_decimal_separator(series: pd.Series) -> str:
    """Infer ``','`` (European: 1.299,00) or ``'.'`` (Anglo: 1,299.00) for a
    column, by counting values that can only be read one way. Defaults to
    ``'.'`` when nothing is decisive."""
    text = _as_text(series).dropna().astype(str)
    if text.empty:
        return "."
    eu = int(text.map(lambda v: bool(_EU_DECIMAL_RE.match(v))).sum())
    us = int(text.map(lambda v: bool(_US_DECIMAL_RE.match(v))).sum())
    return "," if eu > us else "."


def parse_numeric_series(
    series: pd.Series,
    *,
    decimal: str | None = None,
    percent_to_fraction: bool = True,
) -> pd.Series:
    """Coerce a messy money/quantity column to float.

    Handles currency symbols and codes, thousands separators in either
    convention, percent signs, accounting-style ``(1,234)`` negatives, and the
    Unicode minus. Anything genuinely unparseable becomes NaN — never a guess.
    """
    if pd.api.types.is_numeric_dtype(series) and not pd.api.types.is_bool_dtype(series):
        return series.astype("float64")

    sep = decimal or infer_decimal_separator(series)
    text = _as_text(series)

    def _one(value: Any) -> float:
        if value is None or (not isinstance(value, str) and pd.isna(value)):
            return np.nan
        if isinstance(value, bool):
            return np.nan
        if isinstance(value, (int, float, np.integer, np.floating)):
            return float(value)

        raw = str(value).strip().replace("−", "-").replace(" ", " ")
        if not raw or normalize_arabic(raw).casefold() in NULL_TOKENS:
            return np.nan

        negative = False
        if raw.startswith("(") and raw.endswith(")"):
            negative, raw = True, raw[1:-1].strip()
        is_percent = "%" in raw or "٪" in raw

        cleaned = _DECORATION_RE.sub("", raw).strip()
        # Anything still carrying a letter, an internal sign or a stray symbol
        # is not a number — it is a code, a date, or free text. Reject it
        # outright rather than salvaging digits out of it.
        if not _STRICT_NUMBER_RE.match(cleaned):
            return np.nan

        if sep == "," or _DECIMAL_COMMA_RE.match(cleaned):
            cleaned = cleaned.replace(".", "").replace(",", ".")
        else:
            cleaned = cleaned.replace(",", "")

        try:
            number = float(cleaned)
        except ValueError:
            return np.nan

        if is_percent and percent_to_fraction:
            number /= 100.0
        return -number if negative else number

    return pd.Series([_one(v) for v in text], index=series.index, dtype="float64")


def infer_dayfirst(series: pd.Series) -> bool | None:
    """Resolve the DD/MM vs MM/DD ambiguity from the data itself.

    Returns True (day first), False (month first), or ``None`` when the column
    is genuinely ambiguous — every value parses both ways, so no amount of
    inspection can decide. Callers surface ``None`` as a warning rather than
    silently picking, because guessing wrong shifts up to 12/31 of the rows to
    the wrong month and nothing downstream would ever notice.
    """
    text = _as_text(series).dropna().astype(str)
    first_gt_12 = second_gt_12 = 0
    for value in text:
        m = _DMY_RE.match(value)
        if not m:
            continue
        a, b = int(m.group(1)), int(m.group(2))
        if a > 12 >= b:
            first_gt_12 += 1
        elif b > 12 >= a:
            second_gt_12 += 1
    if first_gt_12 and not second_gt_12:
        return True
    if second_gt_12 and not first_gt_12:
        return False
    if first_gt_12 and second_gt_12:
        return None  # internally contradictory — two formats mixed in one column
    # No value has a component above 12: every date parses both ways. If the
    # column contains slash-style dates at all, that is genuinely undecidable.
    has_ambiguous = any(_DMY_RE.match(v) for v in text)
    return None if has_ambiguous else False


def parse_datetime_series(
    series: pd.Series, *, dayfirst: bool | None = None, fmt: str | None = None
) -> pd.Series:
    """Coerce a column to datetime64, handling mixed string formats, Excel
    serial numbers and epoch timestamps. Unparseable values become NaT."""
    if pd.api.types.is_datetime64_any_dtype(series):
        return series

    if fmt:
        return pd.to_datetime(_as_text(series), format=fmt, errors="coerce")

    # Numeric columns are serials or epochs, not date strings.
    numeric = pd.to_numeric(_as_text(series), errors="coerce")
    non_null = numeric.dropna()
    if len(non_null) and numeric.notna().sum() >= series.notna().sum() * 0.9:
        median = float(non_null.abs().median())
        if _EXCEL_SERIAL_RANGE[0] <= median <= _EXCEL_SERIAL_RANGE[1]:
            return pd.to_datetime(numeric, unit="D", origin="1899-12-30", errors="coerce")
        if _EPOCH_MILLIS_RANGE[0] <= median <= _EPOCH_MILLIS_RANGE[1]:
            return pd.to_datetime(numeric, unit="ms", errors="coerce")
        if _EPOCH_SECONDS_RANGE[0] <= median <= _EPOCH_SECONDS_RANGE[1]:
            return pd.to_datetime(numeric, unit="s", errors="coerce")

    resolved = infer_dayfirst(series) if dayfirst is None else dayfirst
    text = _as_text(series)

    # Parse year-first values separately. `dayfirst` is inferred from the
    # slash-style values in the column, and applying it to an ISO string
    # silently reinterprets 2024-01-05 as 5 January vs 1 May — a one-line
    # setting that moves up to 11/12 of the rows into the wrong month with
    # nothing downstream able to notice.
    is_ymd = text.map(lambda v: bool(_YMD_RE.match(v)) if isinstance(v, str) else False)
    parsed = pd.to_datetime(
        text.where(~is_ymd), errors="coerce", dayfirst=bool(resolved), format="mixed"
    )
    if is_ymd.any():
        iso = pd.to_datetime(text.where(is_ymd), errors="coerce", format="mixed")
        parsed = parsed.fillna(iso)
    return parsed


def parse_boolean_series(series: pd.Series) -> pd.Series:
    """Coerce Y/N, yes/no, true/false, 1/0 (and Arabic نعم/لا) to nullable
    boolean. Unrecognised values become NA."""
    if pd.api.types.is_bool_dtype(series):
        return series.astype("boolean")

    def _one(value: Any) -> Any:
        if value is None or (not isinstance(value, str) and pd.isna(value)):
            return pd.NA
        if isinstance(value, (bool, np.bool_)):
            return bool(value)
        token = normalize_arabic(str(value)).strip().casefold()
        if token in _TRUE_TOKENS:
            return True
        if token in _FALSE_TOKENS:
            return False
        return pd.NA

    return pd.Series([_one(v) for v in series], index=series.index, dtype="boolean")


def category_key(value: Any) -> str:
    """Normalized grouping key for near-duplicate category detection:
    case-folded, whitespace-collapsed, punctuation-stripped, Arabic-normalized.
    ``"Cairo"``, ``"cairo "`` and ``"CAIRO"`` share a key; ``"Cairo"`` and
    ``"Giza"`` do not — so merging on this key can never fuse two genuinely
    different categories.
    """
    text = normalize_arabic(str(value)).casefold()
    text = re.sub(r"[^\w\s]", "", text, flags=re.UNICODE)
    return re.sub(r"\s+", " ", text).strip()


