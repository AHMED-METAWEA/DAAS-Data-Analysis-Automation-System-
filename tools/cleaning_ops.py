"""Deterministic cleaning operators + the measuring apply engine.

This is the execution layer of the cleaning agent. The planner selects and
parameterises operators from ``REGISTRY``; nothing here is generated by an LLM,
so every transformation is deterministic, unit-testable, and re-runnable.

Two rules make the whole thing trustworthy:

1. **Operators never report their own effects.** An operator is a pure
   ``(df, columns, params) -> df`` function. ``apply_step`` diffs the frame
   before and after and *measures* what changed. A buggy operator therefore
   produces a wrong-looking ledger and trips the validator, instead of a
   confident log line that isn't true.

2. **Operators never fabricate values to keep a metric flat.** Parsing
   operators turn genuinely unparseable input into NULL and say so
   (``may_introduce_nulls``). Filling those NULLs is a separate, explicit
   ``impute`` step that the plan has to ask for. The old pipeline instructed
   the LLM to back-fill unparseable dates specifically so the null check would
   stay quiet — that is data fabrication, and it is now structurally
   impossible to do by accident.

Index contract: ``apply_plan`` resets to a clean RangeIndex once, then every
operator must return a frame whose index is a subset of the one it received,
with no duplicates and no new labels. That is what lets ``_diff`` align rows
and count real value changes rather than guessing.
"""

