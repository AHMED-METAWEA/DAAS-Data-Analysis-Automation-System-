def _targets(df: pd.DataFrame, columns: list[str]) -> list[str]:
    return [c for c in columns if c in df.columns]


def op_standardize_null_placeholders(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    df = df.copy()
    for col in _targets(df, columns):
        mask = null_token_mask(df[col])
        if not mask.any():
            continue
        try:
            df[col] = df[col].mask(mask)
        except (TypeError, ValueError):
            # Mixed-dtype columns can't always hold their own NA — fall back
            # to object, which always can.
            df[col] = df[col].astype(object).mask(mask, other=None)
    return df


def op_replace_sentinels(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    values = params.get("values") or list(COMMON_SENTINELS)
    wanted = {float(v) for v in values}
    df = df.copy()
    for col in _targets(df, columns):
        numeric = pd.to_numeric(_as_text(df[col]), errors="coerce")
        mask = numeric.isin(wanted).fillna(False)
        if mask.any():
            df[col] = df[col].mask(mask)
    return df


def op_trim_whitespace(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    df = df.copy()
    for col in _targets(df, columns):
        df[col] = df[col].map(
            lambda v: re.sub(r"\s+", " ", v).strip() if isinstance(v, str) else v
        )
    return df


def op_parse_numeric(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    df = df.copy()
    for col in _targets(df, columns):
        df[col] = parse_numeric_series(
            df[col],
            decimal=params.get("decimal"),
            percent_to_fraction=bool(params.get("percent_to_fraction", True)),
        )
    return df


def op_parse_datetime(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    df = df.copy()
    for col in _targets(df, columns):
        df[col] = parse_datetime_series(
            df[col], dayfirst=params.get("dayfirst"), fmt=params.get("format")
        )
    return df


def op_parse_boolean(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    df = df.copy()
    for col in _targets(df, columns):
        df[col] = parse_boolean_series(df[col])
    return df


def op_cast_integer(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    """Narrow a float column back to nullable Int64 when every value is whole.

    Counterpart to the old blanket ``astype('float64')`` widening, which turned
    every integer id in the dataset into ``1001.0`` — including columns with no
    nulls and nothing to fix — and carried that representation into the DDL and
    into every join key.
    """
    df = df.copy()
    for col in _targets(df, columns):
        numeric = pd.to_numeric(_as_text(df[col]), errors="coerce")
        finite = numeric.dropna()
        if finite.empty or not bool(np.isfinite(finite).all()) or not bool((finite % 1 == 0).all()):
            continue
        df[col] = numeric.astype("Int64")
    return df


def op_impute(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    strategy = str(params.get("strategy", "median")).lower()
    max_missing_pct = float(params.get("max_missing_pct", 50.0))
    df = df.copy()

    for col in _targets(df, columns):
        series = df[col]
        if series.isna().mean() * 100 > max_missing_pct:
            # Imputing a majority-missing column manufactures the column.
            continue
        if strategy == "constant":
            filled = series.fillna(params.get("value"))
        elif strategy == "ffill":
            filled = series.ffill()
        elif strategy == "bfill":
            filled = series.bfill()
        elif strategy == "mode":
            modes = series.dropna().mode()
            filled = series.fillna(modes.iloc[0]) if len(modes) else series
        elif strategy in ("mean", "median"):
            numeric = pd.to_numeric(series, errors="coerce")
            if numeric.dropna().empty:
                continue
            value = numeric.mean() if strategy == "mean" else numeric.median()
            filled = numeric.fillna(value)
        else:
            continue
        df[col] = filled
    return df


def op_flag_missing(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    df = df.copy()
    for col in _targets(df, columns):
        df[f"{col}__is_missing"] = df[col].isna()
    return df


def op_harmonize_case(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    style = str(params.get("style", "title")).lower()
    fn = {"lower": str.lower, "upper": str.upper, "title": str.title}.get(style, str.title)
    df = df.copy()
    for col in _targets(df, columns):
        df[col] = df[col].map(lambda v: fn(v) if isinstance(v, str) else v)
    return df


def op_harmonize_categories(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    """Fold spelling/case/whitespace variants of the same category onto its most
    common spelling. Only values sharing a normalized key are ever merged."""
    df = df.copy()
    for col in _targets(df, columns):
        series = df[col]
        text = series.where(series.map(lambda v: isinstance(v, str)))
        if text.dropna().empty:
            continue
        keys = text.map(lambda v: category_key(v) if isinstance(v, str) else None)
        canonical: dict[str, str] = {}
        for key, group in text.dropna().groupby(keys.dropna()):
            counts = group.value_counts()
            top = counts.index[0]
            if len(counts) > 1:
                canonical[str(key)] = str(top)
        if canonical:
            df[col] = series.map(
                lambda v: canonical.get(category_key(v), v) if isinstance(v, str) else v
            )
    return df


def op_replace_values(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    mapping = params.get("mapping") or {}
    if not isinstance(mapping, dict) or not mapping:
        return df
    df = df.copy()
    for col in _targets(df, columns):
        df[col] = df[col].map(lambda v: mapping.get(str(v), v) if not pd.isna(v) else v)
    return df


def op_drop_duplicate_rows(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    subset = _targets(df, columns) or None
    return df.drop_duplicates(subset=subset, keep=params.get("keep", "first"))


def op_drop_duplicate_keys(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    subset = _targets(df, columns)
    if not subset:
        return df
    return df.drop_duplicates(subset=subset, keep=params.get("keep", "first"))


def op_flag_duplicate_keys(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    subset = _targets(df, columns)
    if not subset:
        return df
    df = df.copy()
    name = params.get("flag_column") or f"{'_'.join(subset)}__is_duplicate_key"
    df[name] = df.duplicated(subset=subset, keep=False)
    return df


def op_drop_column(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    targets = _targets(df, columns)
    return df.drop(columns=targets) if targets else df


def _outlier_mask(series: pd.Series, method: str, factor: float) -> pd.Series:
    numeric = pd.to_numeric(series, errors="coerce")
    finite = numeric.dropna()
    if len(finite) < 4:
        return pd.Series(False, index=series.index)
    if method == "zscore":
        std = finite.std()
        if not std:
            return pd.Series(False, index=series.index)
        return ((numeric - finite.mean()).abs() / std > factor).fillna(False)
    if method == "modified_zscore":
        median = finite.median()
        mad = (finite - median).abs().median()
        if not mad:
            return pd.Series(False, index=series.index)
        return ((0.6745 * (numeric - median) / mad).abs() > factor).fillna(False)
    q1, q3 = finite.quantile(0.25), finite.quantile(0.75)
    iqr = q3 - q1
    if not iqr:
        return pd.Series(False, index=series.index)
    return ((numeric < q1 - factor * iqr) | (numeric > q3 + factor * iqr)).fillna(False)


def op_flag_outliers(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    """Mark statistical outliers in a new boolean column. Deliberately does not
    modify the values: on skewed business data (order value, revenue) an IQR
    fence flags a long tail of legitimate large orders, and capping them
    rewrites real observations into ones that never occurred."""
    method = str(params.get("method", "iqr")).lower()
    factor = float(params.get("factor", 1.5 if method == "iqr" else 3.0))
    df = df.copy()
    for col in _targets(df, columns):
        df[f"{col}__is_outlier"] = _outlier_mask(df[col], method, factor)
    return df


def op_clip_range(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    """Clamp values to a *domain* bound the plan states explicitly (e.g. a
    discount percentage cannot exceed 100). Not a statistical fence."""
    low, high = params.get("min"), params.get("max")
    if low is None and high is None:
        return df
    df = df.copy()
    for col in _targets(df, columns):
        numeric = pd.to_numeric(df[col], errors="coerce")
        if numeric.dropna().empty:
            continue
        df[col] = numeric.clip(lower=low, upper=high)
    return df


def op_flag_range_violation(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    low, high = params.get("min"), params.get("max")
    df = df.copy()
    for col in _targets(df, columns):
        numeric = pd.to_numeric(df[col], errors="coerce")
        bad = pd.Series(False, index=df.index)
        if low is not None:
            bad |= (numeric < float(low)).fillna(False)
        if high is not None:
            bad |= (numeric > float(high)).fillna(False)
        df[f"{col}__out_of_range"] = bad
    return df


def op_flag_arithmetic_violation(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    """Flag rows where a stated cross-column identity fails, e.g.
    ``line_total = quantity × unit_price``. These rows are real data errors —
    the profiler already detects such identities; nothing used to act on them.
    """
    left, right = params.get("left"), params.get("right")
    result = params.get("result") or (columns[0] if columns else None)
    operator = str(params.get("operator", "*"))
    tolerance = float(params.get("tolerance", 0.01))
    if not (left and right and result) or not all(c in df.columns for c in (left, right, result)):
        return df

    df = df.copy()
    a = pd.to_numeric(df[left], errors="coerce")
    b = pd.to_numeric(df[right], errors="coerce")
    c = pd.to_numeric(df[result], errors="coerce")
    expected = a * b if operator == "*" else a + b if operator == "+" else a - b
    denominator = c.abs().where(c.abs() > 0, other=np.nan)
    relative = (expected - c).abs() / denominator
    mismatch = (relative > tolerance).fillna(False) & expected.notna() & c.notna()
    df[f"{result}__mismatch"] = mismatch
    return df


def op_recompute_arithmetic(df: pd.DataFrame, columns: list[str], params: dict) -> pd.DataFrame:
    """Overwrite a derived column from its inputs where the identity fails.
    Opt-in: only correct when the inputs are known to be the source of truth."""
    left, right = params.get("left"), params.get("right")
    result = params.get("result") or (columns[0] if columns else None)
    operator = str(params.get("operator", "*"))
    tolerance = float(params.get("tolerance", 0.01))
    if not (left and right and result) or not all(c in df.columns for c in (left, right, result)):
        return df

    df = df.copy()
    a = pd.to_numeric(df[left], errors="coerce")
    b = pd.to_numeric(df[right], errors="coerce")
    c = pd.to_numeric(df[result], errors="coerce")
    expected = a * b if operator == "*" else a + b if operator == "+" else a - b
    denominator = c.abs().where(c.abs() > 0, other=np.nan)
    mismatch = (
        ((expected - c).abs() / denominator > tolerance).fillna(False)
        & expected.notna()
        & c.notna()
    )
    df[result] = c.mask(mismatch, expected)
    return df


