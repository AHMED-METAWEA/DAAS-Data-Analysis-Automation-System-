def order_steps(steps: list[CleaningStep]) -> list[CleaningStep]:
    """Sort a plan into the safe execution order and renumber it.

    Applied to every plan regardless of origin. A planner LLM has no reason to
    know that de-duplication must precede imputation, and asking it to get the
    ordering right is a needless dependency on the model behaving — the
    ordering is a property of the operators, so the system owns it.

    Free-text steps sort last: they run as generated code after the operators,
    on the already-cleaned frame.
    """
    ordered = sorted(
        steps, key=lambda s: OP_EXECUTION_ORDER.get(s.op, 999 if not s.op else 100)
    )
    for position, step in enumerate(ordered, start=1):
        step.id = str(position)
    return ordered


def operator_catalog() -> str:
    """Render the registry as the operator menu shown to the planner LLM."""
    lines = []
    for spec, _ in REGISTRY.values():
        params = ", ".join(
            f"{p.name}"
            + (f"={p.default!r}" if p.default is not None else "")
            + ("*" if p.required else "")
            + (f" one of {p.choices}" if p.choices else "")
            for p in spec.params
        )
        lines.append(f"- {spec.name}({params or 'no params'}): {spec.summary}")
    return "\n".join(lines)


def validate_step(step: CleaningStep, df_columns: list[str] | None = None) -> str | None:
    """Check a planned step against the registry *before* running anything.
    Returns an error string, or None when the step is well-formed."""
    entry = REGISTRY.get(step.op)
    if entry is None:
        return f"unknown operator '{step.op}'"
    spec, _ = entry

    if spec.requires_column and not step.columns:
        return f"operator '{step.op}' requires at least one target column"
    if step.columns and not spec.accepts_multiple_columns and len(step.columns) > 1:
        return f"operator '{step.op}' accepts a single column, got {len(step.columns)}"
    if df_columns is not None:
        missing = [c for c in step.columns if c not in df_columns]
        if missing and len(missing) == len(step.columns):
            return f"column(s) {missing} are not in the table"

    known = {p.name for p in spec.params}
    unknown = set(step.params) - known
    if unknown:
        return f"operator '{step.op}' got unknown parameter(s) {sorted(unknown)}"
    for p in spec.params:
        if p.required and step.params.get(p.name) is None:
            return f"operator '{step.op}' requires parameter '{p.name}'"
        value = step.params.get(p.name)
        if value is not None and p.choices and value not in p.choices:
            return f"parameter '{p.name}' must be one of {p.choices}, got {value!r}"
    return None


