def _changed_mask(before: pd.DataFrame, after: pd.DataFrame) -> pd.DataFrame:
    """Elementwise "did this cell's value change" over aligned frames.
    NaN==NaN counts as unchanged; a pure dtype change (1001 -> 1001.0) does not
    count as a value change and is recorded separately."""
    before_null, after_null = before.isna(), after.isna()
    equal = pd.DataFrame(False, index=before.index, columns=before.columns)
    for col in before.columns:
        live = ~(before_null[col] | after_null[col])
        if not live.any():
            continue
        left, right = before.loc[live, col], after.loc[live, col]
        try:
            equal.loc[live, col] = np.asarray(left.to_numpy() == right.to_numpy(), dtype=bool)
        except (TypeError, ValueError):
            equal.loc[live, col] = (
                left.astype(str).to_numpy() == right.astype(str).to_numpy()
            )
    both_null = before_null & after_null
    return ~both_null & ~equal


def _sample_changes(
    before: pd.DataFrame, after: pd.DataFrame, changed: pd.DataFrame
) -> list[CellChange]:
    samples: list[CellChange] = []
    for col in changed.columns:
        for idx in changed.index[changed[col]][:2]:
            samples.append(
                CellChange(
                    row=str(idx), column=str(col),
                    before=_jsonable(before.at[idx, col]),
                    after=_jsonable(after.at[idx, col]),
                )
            )
            if len(samples) >= _MAX_SAMPLES:
                return samples
    return samples


def _jsonable(value: Any) -> Any:
    if value is None or (not isinstance(value, str) and pd.isna(value)):
        return None
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return float(value)
    if isinstance(value, (np.bool_,)):
        return bool(value)
    if isinstance(value, (pd.Timestamp,)):
        return value.isoformat()
    return value if isinstance(value, (int, float, bool, str)) else str(value)


def _summarize(ledger: StepLedger) -> str:
    """One log line, built entirely from measured counts."""
    where = ", ".join(ledger.columns) if ledger.columns else "the table"
    bits: list[str] = []
    if ledger.rows_removed:
        bits.append(f"removed {ledger.rows_removed} row(s)")
    if ledger.nulls_filled:
        bits.append(f"filled {ledger.nulls_filled} missing value(s)")
    if ledger.nulls_introduced:
        bits.append(f"set {ledger.nulls_introduced} unparseable/placeholder value(s) to NULL")
    changed_only = ledger.cells_changed - ledger.nulls_filled - ledger.nulls_introduced
    if changed_only > 0:
        bits.append(f"rewrote {changed_only} value(s)")
    if ledger.columns_added:
        bits.append(f"added column(s) {', '.join(ledger.columns_added)}")
    if ledger.columns_dropped:
        bits.append(f"dropped column(s) {', '.join(ledger.columns_dropped)}")
    if ledger.dtype_changes:
        bits.append(
            "changed type of "
            + ", ".join(f"{c} -> {t}" for c, t in ledger.dtype_changes.items())
        )
    if not bits:
        return f"{ledger.op} on {where}: no change needed"
    return f"{ledger.op} on {where}: " + "; ".join(bits)


def apply_step(
    df: pd.DataFrame, step: CleaningStep, *, protected_columns: set[str] | None = None
) -> tuple[pd.DataFrame, StepLedger]:
    """Run one typed step and measure exactly what it did.

    On any operator error the original frame is returned untouched and the
    failure is recorded — one bad step never corrupts the run or halts the
    remaining steps.
    """
    protected = protected_columns or set()
    ledger = StepLedger(
        step_id=step.id, op=step.op, columns=list(step.columns),
        params=dict(step.params), rows_before=len(df), rows_after=len(df),
    )

    error = validate_step(step, list(df.columns))
    if error:
        ledger.applied = False
        ledger.error = error
        ledger.summary = f"[failed] {step.op}: {error}"
        return df, ledger

    unsafe_keys = sorted(set(step.columns) & protected)
    if unsafe_keys and step.op not in KEY_SAFE_OPS:
        ledger.applied = False
        ledger.skipped_reason = (
            f"'{step.op}' would change the representation of join key(s) "
            f"{unsafe_keys}, which can orphan rows in the related table"
        )
        ledger.summary = f"[skipped] {step.op}: {ledger.skipped_reason}"
        return df, ledger

    _, fn = REGISTRY[step.op]
    try:
        result = fn(df, list(step.columns), dict(step.params))
    except Exception as exc:  # operator bug or hostile data — never fatal
        ledger.applied = False
        ledger.error = f"{type(exc).__name__}: {exc}"
        ledger.summary = f"[failed] {step.op}: {ledger.error}"
        return df, ledger

    if not isinstance(result, pd.DataFrame):
        ledger.applied = False
        ledger.error = f"operator returned {type(result).__name__}, not a DataFrame"
        ledger.summary = f"[failed] {step.op}: {ledger.error}"
        return df, ledger

    # The result's index must be the input's index with rows only removed —
    # same labels, same order. Anything else means rows were reordered,
    # relabelled or invented, and every value-level comparison below would then
    # be aligning the wrong rows against each other.
    expected_index = df.index[df.index.isin(result.index)]
    if result.index.has_duplicates or not result.index.equals(expected_index):
        ledger.applied = False
        ledger.error = (
            "operator broke the row-identity contract: the returned rows are not the "
            "input rows in their original order"
        )
        ledger.summary = f"[failed] {step.op}: {ledger.error}"
        return df, ledger

    # ── Measure ────────────────────────────────────────────────────────
    ledger.rows_after = len(result)
    ledger.rows_removed = max(0, len(df) - len(result))
    ledger.rows_added = max(0, len(result) - len(df))
    ledger.columns_added = [c for c in result.columns if c not in df.columns]
    ledger.columns_dropped = [c for c in df.columns if c not in result.columns]

    common_idx = df.index.intersection(result.index)
    common_cols = [c for c in df.columns if c in result.columns]
    if len(common_idx) and common_cols:
        before = df.loc[common_idx, common_cols]
        after = result.loc[common_idx, common_cols]
        changed = _changed_mask(before, after)
        ledger.cells_changed = int(changed.to_numpy().sum())
        before_null, after_null = before.isna(), after.isna()
        ledger.nulls_filled = int((before_null & ~after_null).to_numpy().sum())
        ledger.nulls_introduced = int((~before_null & after_null).to_numpy().sum())
        ledger.samples = _sample_changes(before, after, changed)
        ledger.dtype_changes = {
            str(c): str(result[c].dtype)
            for c in common_cols
            if str(df[c].dtype) != str(result[c].dtype)
        }

    ledger.summary = _summarize(ledger)
    return result, ledger


def apply_plan(
    df: pd.DataFrame,
    steps: list[CleaningStep],
    *,
    protected_columns: set[str] | None = None,
    table_name: str = "",
) -> tuple[pd.DataFrame, CleaningLedger]:
    """Run a typed cleaning plan end to end, returning the cleaned frame and
    the measured ledger. Steps run in order; a failing step is skipped and
    recorded, never fatal."""
    working = df.reset_index(drop=True)
    ledger = CleaningLedger(table_name=table_name, rows_before=len(working))

    for step in steps:
        working, step_ledger = apply_step(working, step, protected_columns=protected_columns)
        ledger.steps.append(step_ledger)

    ledger.rows_after = len(working)
    return working, ledger
